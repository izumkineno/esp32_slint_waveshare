//! Packed ST77916 vendor initialization sequences.
//!
//! Each record is encoded as:
//! `command, data_len | 0x80_if_delay, data..., delay_ms_le_if_present`.

#[derive(Clone, Copy)]
pub(crate) struct InitCommand<'a> {
    pub(crate) command: u8,
    pub(crate) data: &'a [u8],
    pub(crate) delay_ms: u16,
}

pub(crate) struct InitCommandIter<'a> {
    bytes: &'a [u8],
    offset: usize,
}

pub(crate) fn iter(bytes: &'static [u8]) -> InitCommandIter<'static> {
    InitCommandIter { bytes, offset: 0 }
}

impl<'a> Iterator for InitCommandIter<'a> {
    type Item = InitCommand<'a>;

    fn next(&mut self) -> Option<Self::Item> {
        let command = *self.bytes.get(self.offset)?;
        let flags = *self.bytes.get(self.offset + 1)?;
        self.offset += 2;

        let data_len = (flags & 0x7F) as usize;
        let data_start = self.offset;
        let data_end = data_start.checked_add(data_len)?;
        let data = self.bytes.get(data_start..data_end)?;
        self.offset = data_end;

        let delay_ms = if flags & 0x80 != 0 {
            let delay_end = self.offset.checked_add(2)?;
            let delay = self.bytes.get(self.offset..delay_end)?;
            self.offset = delay_end;
            u16::from_le_bytes([delay[0], delay[1]])
        } else {
            0
        };

        Some(InitCommand {
            command,
            data,
            delay_ms,
        })
    }
}

